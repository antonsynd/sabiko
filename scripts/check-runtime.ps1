<#
.SYNOPSIS
  Windows counterpart of check-runtime.sh: assembles, verifies and runs the committed IL
  probes under runtime\tests against tools\runtime\Sabiko.Runtime.dll. format.il must print
  exactly format.expected (generated by rustc); panic.il must exit 101 with the panic and its
  location on stderr.
#>
$ErrorActionPreference = 'Stop'
$Root = Resolve-Path (Join-Path $PSScriptRoot '..')
. (Join-Path $Root 'tools\env.ps1')
$Runtime = Join-Path $env:SABIKO_RUNTIME_DIR 'Sabiko.Runtime.dll'
if (-not (Test-Path $Runtime)) { throw "runtime: $Runtime missing; run scripts\build-runtime.ps1" }

# Assembles runtime\tests\<Name>.il into target\il\<Name>\<Name>.dll, verifies it and returns the dll path.
function Build($Name) {
  $out = Join-Path $Root "target\il\$Name"
  New-Item -ItemType Directory -Force -Path $out | Out-Null
  $dll = Join-Path $out "$Name.dll"
  # Out-Host keeps tool output off the pipeline, so the function returns only the dll path.
  ilasm -quiet -exe "-output:$dll" (Join-Path $Root "runtime\tests\$Name.il") | Out-Host
  if ($LASTEXITCODE -ne 0) { throw "ilasm failed for $Name" }
  ilverify -r $Runtime $dll | Out-Host
  if ($LASTEXITCODE -ne 0) { throw "ilverify failed for $Name" }
  Copy-Item (Join-Path $Root 'spike\hello.runtimeconfig.json') (Join-Path $out "$Name.runtimeconfig.json")
  Copy-Item $Runtime $out
  $dll
}

# Runs a dll with stdout/stderr redirected to files (raw bytes, no console re-encoding); returns the exit code.
function Run($Dll, $StdOut, $StdErr) {
  $p = Start-Process -FilePath $env:SABIKO_DOTNET -ArgumentList "`"$Dll`"" -NoNewWindow -Wait -PassThru `
    -RedirectStandardOutput $StdOut -RedirectStandardError $StdErr
  $p.ExitCode
}
# Reads a UTF-8 text file with line endings normalised to "\n" (format.expected may be checked out with CRLF).
function ReadLf($Path) { [System.IO.File]::ReadAllText($Path, [System.Text.UTF8Encoding]::new($false)) -replace "`r`n", "`n" }

$ok = $true
$dll = Build 'format'
$code = Run $dll (Join-Path $Root 'target\il\format\stdout.txt') (Join-Path $Root 'target\il\format\stderr.txt')
$actual = ReadLf (Join-Path $Root 'target\il\format\stdout.txt')
$expected = ReadLf (Join-Path $Root 'runtime\tests\format.expected')
if ($code -ne 0 -or $actual -ne $expected) { Write-Error "runtime format: output mismatch (exit $code)"; $ok = $false } else { Write-Host 'runtime format: ok' }

$dll = Build 'panic'
$stderrFile = Join-Path $Root 'target\il\panic\stderr.txt'
$stdoutFile = Join-Path $Root 'target\il\panic\stdout.txt'
$code = Run $dll $stdoutFile $stderrFile
$stderr = ReadLf $stderrFile
if ($code -eq 101 -and $stderr -eq "thread 'main' panicked at src/probe.sabi:7:5:`nboom`n" -and ((ReadLf $stdoutFile) -eq "before`n")) {
  Write-Host 'runtime panic: ok'
} else {
  Write-Error "runtime panic: expected exit 101 with the located 'boom' report on stderr, got exit ${code}: $stderr"; $ok = $false
}
if (-not $ok) { exit 1 }
